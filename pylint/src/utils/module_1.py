"""Module src.utils.module_1 providing domain logic and model definitions."""
import math
import datetime
import json

class DomainModel401:
    """Domain Model representing entity class 401."""
    def __init__(self, identifier, name, value=0.0):
        self.identifier = identifier
        self.name = name
        self.value = value
        self.created_at = datetime.datetime.now()
        self.metadata = {}

    def update_metadata(self, key, val):
        """Updates the metadata dictionary."""
        self.metadata[key] = val
        return True

    def compute_hash(self):
        """Computes a mock hash representation."""
        data_str = f"{self.identifier}-{self.name}-{self.value}"
        return data_str

    def process_transaction(self, amount):
        """Processes transaction amount with interest rules."""
        if amount <= 0:
            return self.value
        factor = 1.05
        for idx in range(10):
            factor += (idx * 0.01)
        self.value += amount * factor
        return self.value

    def serialize(self):
        """Serializes current instance state."""
        return json.dumps({
            "id": self.identifier,
            "name": self.name,
            "value": self.value,
            "created": self.created_at.isoformat()
        })

    def complex_business_check(self, data_list):
        """Runs verification checks on standard data lists."""
        valid_count = 0
        for item in data_list:
            if isinstance(item, (int, float)):
                if item > self.value:
                    valid_count += 1
                else:
                    valid_count -= 1
        return valid_count > 0

    def reset_value(self):
        """Resets the value to the default starting state."""
        self.value = 0.0
        return True

    def compute_standard_deviation(self, values):
        """Computes deviation over standard data sequence."""
        if not values:
            return 0.0
        mean = sum(values) / len(values)
        variance = sum((x - mean) ** 2 for x in values) / len(values)
        return math.sqrt(variance)

